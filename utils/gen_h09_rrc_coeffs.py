# Python script to generate H09 RRC FIR coefficients
# Using the following RRC parameters:
#   - RRC beta: 0.25
#   - RRC span: 10
#   - Sample per symbol: 8
#   - FIR tap: 81 (10 * 8 + 1)
#   - Bit per coefficient: 18
#   - Fractional bits: 17 (signed Q1.17)
#   - DAC output: I = 16-bit signed, Q = 0 (not used in this file, refer to FPGA/src/H09_pulse_shape.v)
#   - DAC amplitude: 512 (not used in this file, refer to FPGA/src/H09_pulse_shape.v)

from rf_clock.generate_rrc_coefficients import generate_rrc_coefficients
from pathlib import Path
import hashlib
import sqlite3


# Configs
H09_RRC_SAMPLES_PER_SYMBOL = 8
H09_RRC_SPAN_CHIPS = 10
H09_RRC_TAP_COUNT = H09_RRC_SAMPLES_PER_SYMBOL * H09_RRC_SPAN_CHIPS + 1
H09_RRC_TAIL_SAMPLES = H09_RRC_TAP_COUNT - H09_RRC_SAMPLES_PER_SYMBOL
H09_RRC_COEFF_BITS = 18
H09_RRC_FRAC_BITS = 17
H09_RRC_BETA = 0.25

PROJECT_ROOT = Path(__file__).resolve().parents[1]
DATA_DIR = PROJECT_ROOT / "FPGA" / "data"
DATA_DIR.mkdir(parents=True, exist_ok=True)
CONFIG_DATABASE = DATA_DIR / "H09_config.db"
VERILOG_FILE = DATA_DIR / "H09_rrc_coeffs.vh"
VERILOG_FILE_TEMPLATE = """// Generated by gen_h09_rrc_coeffs.py, DO NOT EDIT MANUALLY
// This file contains the RRC FIR coefficients used by H09_rrc_fir
// This file needs to be included in the H09_rrc_fir module, before @always begins

`ifndef H09_RRC_COEFFS_VH
`define H09_RRC_COEFFS_VH

localparam [31:0] H09_RRC_FIR_CONFIG_ID = {H09_CONFIG_ID};
localparam integer H09_RRC_SAMPLES_PER_SYMBOL = {H09_RRC_SAMPLES_PER_SYMBOL};
localparam integer H09_RRC_SPAN_CHIPS = {H09_RRC_SPAN_CHIPS};
localparam integer H09_RRC_TAP_COUNT = {H09_RRC_TAP_COUNT};
localparam integer H09_RRC_TAIL_SAMPLES = {H09_RRC_TAIL_SAMPLES};
localparam integer H09_RRC_COEFF_BITS = {H09_RRC_COEFF_BITS};
localparam integer H09_RRC_FRAC_BITS = {H09_RRC_FRAC_BITS};

(* rom_style = "distributed" *)
reg signed [H09_RRC_COEFF_BITS-1:0] h09_rrc_rom [0:H09_RRC_TAP_COUNT-1];

initial begin
{H09_RRC_COEFF_STR}
end

`endif
"""


# RRC coefficient generation
H09_RRC_COEFF = generate_rrc_coefficients(
    beta = H09_RRC_BETA,
    span_chips = H09_RRC_SPAN_CHIPS,
    samples_per_symbol = H09_RRC_SAMPLES_PER_SYMBOL,
    coeff_bits = H09_RRC_COEFF_BITS,
    frac_bits = H09_RRC_FRAC_BITS
)
H09_RRC_COEFF_STR = "\n".join(
    f"    h09_rrc_rom[{i}] = {'-' if int(value) < 0 else ''}{H09_RRC_COEFF_BITS}'sd{abs(int(value))};"
    for i, value in enumerate(H09_RRC_COEFF)
)
# Validate the coefficients
if len(H09_RRC_COEFF) != H09_RRC_TAP_COUNT:
    raise ValueError("wrong coefficient count")
if H09_RRC_COEFF != H09_RRC_COEFF[::-1]:
    raise ValueError("coefficients are not symmetric")
minimum = -(1 << (H09_RRC_COEFF_BITS - 1))
maximum = (1 << (H09_RRC_COEFF_BITS - 1)) - 1
if any(value < minimum or value > maximum for value in H09_RRC_COEFF):
    raise ValueError("coefficient exceeds signed range")


# Calculate the config ID using the sha256 hash of the RRC parameters
config_text = repr((
    H09_RRC_SAMPLES_PER_SYMBOL,
    H09_RRC_SPAN_CHIPS,
    H09_RRC_TAP_COUNT,
    H09_RRC_TAIL_SAMPLES,
    H09_RRC_COEFF_BITS,
    H09_RRC_FRAC_BITS,
    H09_RRC_BETA,
    tuple(H09_RRC_COEFF),
))
H09_CONFIG_ID = int(hashlib.sha256(config_text.encode("utf-8")).hexdigest(), 16) % (2**32)


# Write the verilog file
VERILOG_FILE.write_text(VERILOG_FILE_TEMPLATE.format(
    H09_CONFIG_ID=H09_CONFIG_ID,
    H09_RRC_SAMPLES_PER_SYMBOL=H09_RRC_SAMPLES_PER_SYMBOL,
    H09_RRC_SPAN_CHIPS=H09_RRC_SPAN_CHIPS,
    H09_RRC_TAP_COUNT=H09_RRC_TAP_COUNT,
    H09_RRC_TAIL_SAMPLES=H09_RRC_TAIL_SAMPLES,
    H09_RRC_COEFF_BITS=H09_RRC_COEFF_BITS,
    H09_RRC_FRAC_BITS=H09_RRC_FRAC_BITS,
    H09_RRC_COEFF_STR=H09_RRC_COEFF_STR
), encoding="utf-8", newline="\n")


# Save to config database
with sqlite3.connect(CONFIG_DATABASE) as conn:
    conn.execute(
        """
        CREATE TABLE IF NOT EXISTS H09_config (
            H09_CONFIG_ID INTEGER PRIMARY KEY NOT NULL, 
            H09_RRC_SAMPLES_PER_SYMBOL INTEGER NOT NULL,
            H09_RRC_SPAN_CHIPS INTEGER NOT NULL,
            H09_RRC_TAP_COUNT INTEGER NOT NULL,
            H09_RRC_TAIL_SAMPLES INTEGER NOT NULL,
            H09_RRC_COEFF_BITS INTEGER NOT NULL,
            H09_RRC_FRAC_BITS INTEGER NOT NULL,
            H09_RRC_BETA REAL NOT NULL
        )
        """
    )
    conn.execute(
        """
        CREATE TABLE IF NOT EXISTS H09_coeff (
            H09_CONFIG_ID INTEGER NOT NULL,
            TAP_INDEX INTEGER NOT NULL,
            COEFFICIENT INTEGER NOT NULL,
            
            PRIMARY KEY (H09_CONFIG_ID, TAP_INDEX),
            FOREIGN KEY (H09_CONFIG_ID) 
                REFERENCES H09_config(H09_CONFIG_ID)
        )
        """
    )
    conn.execute(
        """
        INSERT INTO H09_config (
            H09_CONFIG_ID, 
            H09_RRC_SAMPLES_PER_SYMBOL,
            H09_RRC_SPAN_CHIPS,
            H09_RRC_TAP_COUNT,
            H09_RRC_TAIL_SAMPLES,
            H09_RRC_COEFF_BITS,
            H09_RRC_FRAC_BITS,
            H09_RRC_BETA
        ) VALUES (?, ?, ?, ?, ?, ?, ?, ?)
        ON CONFLICT (H09_CONFIG_ID) DO UPDATE SET
            H09_RRC_SAMPLES_PER_SYMBOL = excluded.H09_RRC_SAMPLES_PER_SYMBOL,
            H09_RRC_SPAN_CHIPS = excluded.H09_RRC_SPAN_CHIPS,
            H09_RRC_TAP_COUNT = excluded.H09_RRC_TAP_COUNT,
            H09_RRC_TAIL_SAMPLES = excluded.H09_RRC_TAIL_SAMPLES,
            H09_RRC_COEFF_BITS = excluded.H09_RRC_COEFF_BITS,
            H09_RRC_FRAC_BITS = excluded.H09_RRC_FRAC_BITS,
            H09_RRC_BETA = excluded.H09_RRC_BETA
        """, 
        (
            H09_CONFIG_ID,
            H09_RRC_SAMPLES_PER_SYMBOL,
            H09_RRC_SPAN_CHIPS,
            H09_RRC_TAP_COUNT,
            H09_RRC_TAIL_SAMPLES,
            H09_RRC_COEFF_BITS,
            H09_RRC_FRAC_BITS,
            H09_RRC_BETA
        )
    )
    conn.execute("DELETE FROM H09_coeff WHERE H09_CONFIG_ID = ?", (H09_CONFIG_ID,))
    conn.executemany(
        """
        INSERT INTO H09_coeff (H09_CONFIG_ID, TAP_INDEX, COEFFICIENT)
        VALUES (?, ?, ?)
        """, 
        [
            (H09_CONFIG_ID, i, int(coeff))
            for i, coeff in enumerate(H09_RRC_COEFF)
        ]
    )