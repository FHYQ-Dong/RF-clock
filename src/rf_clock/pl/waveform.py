"""ARM-side RRC waveform generation.

The PL only transports the samples generated by the ARM.  This module
computes the float64 RRC coefficients from the filter parameters
(:func:`rrc_config`; about 2 ms on the board), generates the H08-compatible
test sequence, and evaluates the RRC convolution.

The reference functions are kept public because they are useful in notebooks
and in tests.  :class:`WaveformGenerator` groups them into the interface used
by the TX buffer driver.
"""

from __future__ import annotations

import hashlib
from dataclasses import dataclass
from typing import Any, Sequence

import numpy as np

from ..generate_rrc_coefficients import generate_rrc_coefficients

DEFAULT_BETA = 0.25
DEFAULT_SPAN_CHIPS = 10
DEFAULT_SAMPLES_PER_SYMBOL = 8
DEFAULT_CONFIG_ID = 2_134_958_710  # rrc_config_id() of the defaults above
DEFAULT_DAC_AMPLITUDE_BASE_2 = 9
DEFAULT_DAC_AMPLITUDE = 1 << DEFAULT_DAC_AMPLITUDE_BASE_2
DEFAULT_CHIP_COUNT = 4096
DEFAULT_LFSR_SEED = 0xACE1


def rrc_config_id(beta: float, span_chips: int, samples_per_symbol: int) -> int:
    """Identifier of an RRC parameter set, recorded with each measurement so
    that TX and RX can be checked to use the same filter.

    The low 32 bits of the SHA-256 of the parameters.  The coefficients are
    not hashed: their last bits may differ between machines.
    """
    tap_count = int(span_chips) * int(samples_per_symbol) + 1
    text = repr((int(samples_per_symbol), int(span_chips), tap_count,
                 tap_count - int(samples_per_symbol), float(beta)))
    return int(hashlib.sha256(text.encode("utf-8")).hexdigest(), 16) % (2**32)


def rrc_config(
    beta: float = DEFAULT_BETA,
    span_chips: int = DEFAULT_SPAN_CHIPS,
    samples_per_symbol: int = DEFAULT_SAMPLES_PER_SYMBOL,
) -> tuple[dict[str, Any], list[float]]:
    """RRC parameters and their ``span_chips * samples_per_symbol + 1``
    float64 coefficients."""

    beta, span_chips, sps = float(beta), int(span_chips), int(samples_per_symbol)
    coeffs = [float(c) for c in generate_rrc_coefficients(
        beta=beta, span_chips=span_chips, samples_per_symbol=sps)]
    tap_count = span_chips * sps + 1
    if len(coeffs) != tap_count:
        raise ValueError(f"expected {tap_count} coefficients, got {len(coeffs)}")
    config: dict[str, Any] = {
        "id": rrc_config_id(beta, span_chips, sps),
        "sps": sps,
        "span_chips": span_chips,
        "tap_count": tap_count,
        "tail_samples": tap_count - sps,
        "beta": beta,
    }
    return config, coeffs


def quantize_output(values, amplitude: float) -> np.ndarray:
    """Scale RRC output to signed 16-bit DAC samples with saturation."""

    amplitude = float(amplitude)
    if amplitude <= 0:
        raise ValueError("amplitude must be positive")
    scaled = np.rint(np.asarray(values, dtype=np.float64) * amplitude)
    return np.clip(scaled, -32768, 32767).astype(np.int16)


def simulate_full_convolution(
    chips: Sequence[int] | np.ndarray,
    coeffs: Sequence[int | float],
    sps: int,
    amplitude: float,
) -> np.ndarray:
    """Simulate the floating-point RRC FIR at the full sample rate.

    The output length is ``(len(chips) - 1) * sps + tap_count``.  The final
    ``tap_count - sps`` samples are the filter tail and are included in the
    waveform sent to the PL.
    """

    if len(chips) == 0:
        raise ValueError("chips cannot be empty")
    sps = int(sps)
    if sps <= 0:
        raise ValueError("sps must be positive")
    if len(coeffs) == 0:
        raise ValueError("coeffs cannot be empty")

    amplitude = float(amplitude)
    if amplitude <= 0:
        raise ValueError("amplitude must be positive")
    input_length = (len(chips) - 1) * sps + 1
    upsampled = np.zeros(input_length, dtype=np.float64)
    upsampled[::sps] = np.asarray(chips, dtype=np.float64)
    accumulator = np.convolve(upsampled, np.asarray(coeffs, dtype=np.float64))
    return quantize_output(accumulator, amplitude)


def simulate_periodic_convolution(
    chips: Sequence[int] | np.ndarray,
    coeffs: Sequence[int | float],
    sps: int,
    amplitude: float,
) -> np.ndarray:
    """One period of the RRC FIR output for ``chips`` repeated forever.

    ``len(chips) * sps`` samples: the filter tail wraps onto the start
    (circular convolution), so copies played back to back (``arm_tx(...,
    repeat=n)``) form one continuous signal.  Sample n matches sample n of
    :func:`simulate_full_convolution` once the wrapped tail has died out.
    """

    if len(chips) == 0:
        raise ValueError("chips cannot be empty")
    sps = int(sps)
    if sps <= 0:
        raise ValueError("sps must be positive")
    period = len(chips) * sps
    upsampled = np.zeros(period, dtype=np.float64)
    upsampled[::sps] = np.asarray(chips, dtype=np.float64)
    full = np.convolve(upsampled, np.asarray(coeffs, dtype=np.float64))
    folded = full[:period].copy()
    for start in range(period, full.size, period):
        part = full[start:start + period]
        folded[: part.size] += part
    return quantize_output(folded, amplitude)


def generate_test_chips(count: int, seed: int = DEFAULT_LFSR_SEED) -> np.ndarray:
    """Generate BPSK chips with the H08 16-bit LFSR convention."""

    count = int(count)
    seed = int(seed)
    if count <= 0:
        raise ValueError("chip count must be positive")
    if not 0 < seed <= 0xFFFF:
        raise ValueError("LFSR seed must be a non-zero 16-bit value")

    chips = np.empty(count, dtype=np.int64)
    state = seed
    for index in range(count):
        chips[index] = 1 if (state & 1) else -1
        feedback = ((state >> 0) ^ (state >> 2) ^ (state >> 3) ^ (state >> 5)) & 1
        state = ((feedback << 15) | (state >> 1)) & 0xFFFF
    return chips


@dataclass
class WaveformGenerator:
    """Generate a quantised RRC TX waveform on the ARM.

    ``generate`` returns one signed 16-bit real (I) sample per element.  The
    uses BPSK, so Q is zero; :meth:`generate_iq` provides the explicit two
    column representation expected by the beat packer.

    ``periodic=True`` gives one period of the repeated sequence instead of a
    burst with RRC tails: ``chip_count * sps`` samples (``chip_count`` beats
    at 8 samples per chip) for ``arm_tx(..., repeat=n)``.
    """

    amplitude: float = DEFAULT_DAC_AMPLITUDE
    chip_count: int = DEFAULT_CHIP_COUNT
    lfsr_seed: int = DEFAULT_LFSR_SEED
    periodic: bool = False
    beta: float = DEFAULT_BETA
    span_chips: int = DEFAULT_SPAN_CHIPS
    samples_per_symbol: int = DEFAULT_SAMPLES_PER_SYMBOL

    def __post_init__(self) -> None:
        self.amplitude = float(self.amplitude)
        self.chip_count = int(self.chip_count)
        self.lfsr_seed = int(self.lfsr_seed)
        if self.amplitude <= 0:
            raise ValueError("amplitude must be positive")
        if self.chip_count <= 0:
            raise ValueError("chip_count must be positive")
        if not 0 < self.lfsr_seed <= 0xFFFF:
            raise ValueError("LFSR seed must be a non-zero 16-bit value")
        self.config, self.coeffs = rrc_config(self.beta, self.span_chips, self.samples_per_symbol)
        self.samples_per_symbol = int(self.config["sps"])

    @property
    def config_id(self) -> int:
        return int(self.config["id"])

    @property
    def tap_count(self) -> int:
        return int(self.config["tap_count"])

    @property
    def tail_samples(self) -> int:
        return int(self.config["tail_samples"])

    @property
    def expected_sample_count(self) -> int:
        tail = 0 if self.periodic else self.tail_samples
        return self.chip_count * self.samples_per_symbol + tail

    def chips(
        self,
        count: int | None = None,
        seed: int | None = None,
    ) -> np.ndarray:
        """Generate chips using this generator's defaults unless overridden."""

        return generate_test_chips(
            self.chip_count if count is None else int(count),
            self.lfsr_seed if seed is None else int(seed),
        )

    def generate(
        self,
        chips: Sequence[int] | np.ndarray | None = None,
        *,
        count: int | None = None,
        seed: int | None = None,
    ) -> np.ndarray:
        """Return the flattened signed-I waveform as an ``int16`` array."""

        if chips is not None and (count is not None or seed is not None):
            raise ValueError("chips cannot be combined with count or seed")
        if chips is None:
            chips = self.chips(count=count, seed=seed)
        convolve = simulate_periodic_convolution if self.periodic else simulate_full_convolution
        return convolve(chips, self.coeffs, self.samples_per_symbol, self.amplitude)

    def generate_iq(
        self,
        chips: Sequence[int] | np.ndarray | None = None,
        *,
        count: int | None = None,
        seed: int | None = None,
    ) -> np.ndarray:
        """Return samples as an ``(N, 2)`` int16 array in I/Q order."""

        samples = self.generate(chips, count=count, seed=seed)
        result = np.zeros((len(samples), 2), dtype=np.int16)
        result[:, 0] = samples
        return result

    def generate_beats(
        self,
        chips: Sequence[int] | np.ndarray | None = None,
        *,
        count: int | None = None,
        seed: int | None = None,
        layout=None,
    ) -> list[int]:
        """Generate and pack the waveform into 256-bit TX beats (TX_LAYOUT
        unless ``layout`` is given)."""

        # Avoid importing the beat codec when a notebook only needs samples.
        from .beats import TX_LAYOUT, BeatPacker

        layout = TX_LAYOUT if layout is None else layout
        samples = self.generate_iq(chips, count=count, seed=seed)
        if self.periodic and len(samples) % layout.lane_count:
            # A padded last beat would put a gap between repeated passes.
            raise ValueError("a periodic waveform must fill whole beats")
        return BeatPacker(layout=layout).pack_samples(samples)


