"""ARM-side RRC waveform generation.

The PL only transports the samples generated by the ARM.  This module is the
small, board-friendly waveform generator: it loads the float64 RRC
coefficients from ``config/RRC_config.db``, generates the H08-compatible test
sequence, and evaluates the RRC convolution. Plotting remains in the utility
script.

The four reference functions are kept as public functions because they are
useful in notebooks and in tests.  :class:`WaveformGenerator` groups them
into the interface used by the TX buffer driver.
"""

from __future__ import annotations

import sqlite3
from contextlib import closing
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Sequence

import numpy as np


PROJECT_ROOT = Path(__file__).resolve().parents[3]
DEFAULT_DATABASE = PROJECT_ROOT / "config" / "RRC_config.db"
DEFAULT_CONFIG_ID = 2_134_958_710
DEFAULT_DAC_AMPLITUDE_BASE_2 = 9
DEFAULT_DAC_AMPLITUDE = 1 << DEFAULT_DAC_AMPLITUDE_BASE_2
DEFAULT_CHIP_COUNT = 4096
DEFAULT_LFSR_SEED = 0xACE1


def load_config(
    database_path: Path | str = DEFAULT_DATABASE,
    config_id: int = DEFAULT_CONFIG_ID,
) -> tuple[dict[str, Any], list[float]]:
    """Load one RRC configuration and its ordered float64 coefficients.

    The SQL and validation intentionally match the existing reference model.
    Keeping this function independent of the plotting utility means the module
    can be copied to a PYNQ image without pulling in Plotly or the old RTL
    comparison code.
    """

    database_path = Path(database_path)
    if not database_path.exists():
        raise FileNotFoundError(f"configuration database not found: {database_path}")

    with closing(sqlite3.connect(database_path)) as conn:
        row = conn.execute(
            """
            SELECT RRC_CONFIG_ID, RRC_SAMPLES_PER_SYMBOL, RRC_SPAN_CHIPS, RRC_TAP_COUNT,
                   RRC_TAIL_SAMPLES, RRC_BETA
            FROM RRC_config
            WHERE RRC_CONFIG_ID = ?
            """,
            (int(config_id),),
        ).fetchone()
        if row is None:
            # Never substitute another configuration: TX and RX must agree on
            # the config ID recorded with every measurement.
            raise ValueError(f"configuration ID not found: {config_id}")

        rows = conn.execute(
            """
            SELECT TAP_INDEX, COEFFICIENT
            FROM RRC_coeff
            WHERE RRC_CONFIG_ID = ?
            ORDER BY TAP_INDEX
            """,
            (int(row[0]),),
        ).fetchall()

    actual_config_id, sps, span_chips, tap_count, tail_samples, beta = row
    coeffs = [float(coefficient) for _, coefficient in rows]
    tap_indices = [int(tap_index) for tap_index, _ in rows]

    if len(coeffs) != int(tap_count):
        raise ValueError(f"expected {tap_count} coefficients, got {len(coeffs)}")
    if tap_indices != list(range(int(tap_count))):
        raise ValueError("tap indices are not contiguous")
    if int(tail_samples) != int(tap_count) - int(sps):
        raise ValueError("RRC_TAIL_SAMPLES does not match tap and sample counts")
    if not np.allclose(coeffs, coeffs[::-1], rtol=0.0, atol=1e-15):
        raise ValueError("FIR coefficients are not symmetric")

    config: dict[str, object] = {
        "id": int(actual_config_id),
        "sps": int(sps),
        "span_chips": int(span_chips),
        "tap_count": int(tap_count),
        "tail_samples": int(tail_samples),
        "beta": float(beta),
    }
    return config, coeffs


def quantize_output(values, amplitude: float) -> np.ndarray:
    """Scale RRC output to signed 16-bit DAC samples with saturation."""

    amplitude = float(amplitude)
    if amplitude <= 0:
        raise ValueError("amplitude must be positive")
    scaled = np.rint(np.asarray(values, dtype=np.float64) * amplitude)
    return np.clip(scaled, -32768, 32767).astype(np.int16)


def simulate_full_convolution(
    chips: Sequence[int] | np.ndarray,
    coeffs: Sequence[int | float],
    sps: int,
    amplitude: float,
) -> np.ndarray:
    """Simulate the floating-point RRC FIR at the full sample rate.

    The output length is ``(len(chips) - 1) * sps + tap_count``.  The final
    ``tap_count - sps`` samples are the filter tail and are included in the
    waveform sent to the PL.
    """

    if len(chips) == 0:
        raise ValueError("chips cannot be empty")
    sps = int(sps)
    if sps <= 0:
        raise ValueError("sps must be positive")
    if len(coeffs) == 0:
        raise ValueError("coeffs cannot be empty")

    amplitude = float(amplitude)
    if amplitude <= 0:
        raise ValueError("amplitude must be positive")
    input_length = (len(chips) - 1) * sps + 1
    upsampled = np.zeros(input_length, dtype=np.float64)
    upsampled[::sps] = np.asarray(chips, dtype=np.float64)
    accumulator = np.convolve(upsampled, np.asarray(coeffs, dtype=np.float64))
    return quantize_output(accumulator, amplitude)


def generate_test_chips(count: int, seed: int = DEFAULT_LFSR_SEED) -> np.ndarray:
    """Generate BPSK chips with the H08 16-bit LFSR convention."""

    count = int(count)
    seed = int(seed)
    if count <= 0:
        raise ValueError("chip count must be positive")
    if not 0 < seed <= 0xFFFF:
        raise ValueError("LFSR seed must be a non-zero 16-bit value")

    chips = np.empty(count, dtype=np.int64)
    state = seed
    for index in range(count):
        chips[index] = 1 if (state & 1) else -1
        feedback = ((state >> 0) ^ (state >> 2) ^ (state >> 3) ^ (state >> 5)) & 1
        state = ((feedback << 15) | (state >> 1)) & 0xFFFF
    return chips


@dataclass
class WaveformGenerator:
    """Generate a quantised RRC TX waveform on the ARM.

    ``generate`` returns one signed 16-bit real (I) sample per element.  The
    uses BPSK, so Q is zero; :meth:`generate_iq` provides the explicit two
    column representation expected by the beat packer.
    """

    database_path: Path | str = DEFAULT_DATABASE
    config_id: int = DEFAULT_CONFIG_ID
    amplitude: float = DEFAULT_DAC_AMPLITUDE
    chip_count: int = DEFAULT_CHIP_COUNT
    lfsr_seed: int = DEFAULT_LFSR_SEED

    def __post_init__(self) -> None:
        self.database_path = Path(self.database_path)
        self.config_id = int(self.config_id)
        self.amplitude = float(self.amplitude)
        self.chip_count = int(self.chip_count)
        self.lfsr_seed = int(self.lfsr_seed)
        if self.amplitude <= 0:
            raise ValueError("amplitude must be positive")
        if self.chip_count <= 0:
            raise ValueError("chip_count must be positive")
        if not 0 < self.lfsr_seed <= 0xFFFF:
            raise ValueError("LFSR seed must be a non-zero 16-bit value")
        self.config, self.coeffs = load_config(self.database_path, self.config_id)

    @property
    def samples_per_symbol(self) -> int:
        return int(self.config["sps"])

    @property
    def tap_count(self) -> int:
        return int(self.config["tap_count"])

    @property
    def tail_samples(self) -> int:
        return int(self.config["tail_samples"])

    @property
    def expected_sample_count(self) -> int:
        return self.chip_count * self.samples_per_symbol + self.tail_samples

    def chips(
        self,
        count: int | None = None,
        seed: int | None = None,
    ) -> np.ndarray:
        """Generate chips using this generator's defaults unless overridden."""

        return generate_test_chips(
            self.chip_count if count is None else int(count),
            self.lfsr_seed if seed is None else int(seed),
        )

    def generate(
        self,
        chips: Sequence[int] | np.ndarray | None = None,
        *,
        count: int | None = None,
        seed: int | None = None,
    ) -> np.ndarray:
        """Return the flattened signed-I waveform as an ``int16`` array."""

        if chips is not None and (count is not None or seed is not None):
            raise ValueError("chips cannot be combined with count or seed")
        if chips is None:
            chips = self.chips(count=count, seed=seed)
        return simulate_full_convolution(
            chips,
            self.coeffs,
            self.samples_per_symbol,
            self.amplitude,
        )

    def generate_iq(
        self,
        chips: Sequence[int] | np.ndarray | None = None,
        *,
        count: int | None = None,
        seed: int | None = None,
    ) -> np.ndarray:
        """Return samples as an ``(N, 2)`` int16 array in I/Q order."""

        samples = self.generate(chips, count=count, seed=seed)
        result = np.zeros((len(samples), 2), dtype=np.int16)
        result[:, 0] = samples
        return result

    def generate_beats(
        self,
        chips: Sequence[int] | np.ndarray | None = None,
        *,
        count: int | None = None,
        seed: int | None = None,
        layout=None,
    ) -> list[int]:
        """Generate and pack the waveform into 256-bit TX beats (TX_LAYOUT
        unless ``layout`` is given)."""

        # Avoid importing the beat codec when a notebook only needs samples.
        from .beats import TX_LAYOUT, BeatPacker

        return BeatPacker(layout=TX_LAYOUT if layout is None else layout).pack_samples(
            self.generate_iq(chips, count=count, seed=seed)
        )


# Friendly aliases for callers that prefer the shorter name.
Waveform = WaveformGenerator
RRCWaveformGenerator = WaveformGenerator


